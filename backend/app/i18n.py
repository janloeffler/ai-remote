CATALOGS = {"en": EN, "de": DE}


def resolve_language(cookie_value: str | None, accept_language: str | None) -> str:
    """Explicit choice (cookie) wins, then the browser's Accept-Language, then English."""
    if cookie_value in SUPPORTED:
        return cookie_value
    for part in (accept_language or "").split(","):
        tag = part.split(";")[0].strip().lower()
        if tag[:2] in SUPPORTED:
            return tag[:2]
    return DEFAULT_LANGUAGE


def translate(lang: str, key: str, **values) -> str:
    text = CATALOGS.get(lang, EN).get(key) or EN.get(key) or key
    return text.format(**values) if values else text


def js_catalog(lang: str) -> dict[str, str]:
    """Raw (unformatted) ``js.*`` templates; app.js substitutes the ``{placeholders}``."""
    table = CATALOGS.get(lang, EN)
    return {key: table.get(key) or EN[key] for key in EN if key.startswith("js.")}
